"""Run ParamMem or ParamMem-DPO with an explicitly selected memory file.

The caller must supply memory generated by the matching SFT or DPO checkpoint.
A filename alone cannot verify the checkpoint provenance.
"""
import argparse
from pathlib import Path

from shared.entrypoints import run_script

SCRIPTS = {"code": "code/main_param.py", "math": "math/mainMath_param.py",
           "qa": "qa/mainQA_parametric.py"}
MEMORY_ARGS = {"code": ("--use_mistakes", "--mistake_json_path"),
               "math": ("--use_expert_module", "--insight_json_path"),
               "qa": ("--use_expert_module", "--insight_json_path")}


def main():
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument("domain", choices=SCRIPTS)
    parser.add_argument("--method", choices=("parammem", "parammem-dpo"), required=True)
    parser.add_argument("--memory-file", type=Path, required=True)
    args, remaining = parser.parse_known_args()
    if not args.memory_file.is_file():
        parser.error(f"memory file does not exist: {args.memory_file}")
    reserved = {"--use_mistakes", "--use_expert_module", "--mistake_json_path", "--insight_json_path"}
    if any(item.split("=", 1)[0] in reserved for item in remaining):
        parser.error("use --memory-file instead of legacy memory arguments")
    if not any(item.split("=", 1)[0] == "--strategy" for item in remaining):
        remaining += ["--strategy", "dot"]
    enable, memory_arg = MEMORY_ARGS[args.domain]
    forwarded = [*remaining, enable, memory_arg, str(args.memory_file)]
    if not any(item.split("=", 1)[0] == "--run_name" for item in remaining):
        forwarded += ["--run_name", f"{args.method}_{args.domain}"]
    if not any(item.split("=", 1)[0] == "--root_dir" for item in remaining):
        forwarded += ["--root_dir", f"results/{args.domain}/{args.method}"]
    print(f"Method: {args.method}; memory: {args.memory_file}")
    return run_script(SCRIPTS[args.domain], forwarded)


if __name__ == "__main__":
    main()
